function transcriptFailure(
  code: TranscriptFailureCode,
  videoId: string | undefined,
  runtime: YoutubeTranscriptRuntime,
  input?: Partial<z.output<typeof youtubeTranscriptInputSchema>>,
  availableTracks: z.output<typeof youtubeTranscriptTrackSchema>[] = [],
  error?: unknown
): YoutubeTranscriptEnvelope {
  const details = FAILURE_DETAILS[code];
  const languageFailure = unavailableLanguageDetails(error);
  const languageFromError = languageFailure?.lang;
  const languagesFromError = languageFailure === undefined
    ? []
    : languageFailure.availableLangs.map((languageCode: string) => ({
        language_code: languageCode,
        language_name: languageCode,
        is_auto_generated: false
      })).filter((track: unknown) => youtubeTranscriptTrackSchema.safeParse(track).success);
  const tracks = availableTracks.length > 0 ? availableTracks : languagesFromError;
  const envelope = errorEnvelope<[]>(
    {
      provider: "youtube",
      recordType: "youtube_transcript",
      ...(videoId === undefined ? {} : { primaryIdentifier: videoId }),
      retrievedAt: readRetrievedAt(runtime),
      ...(videoId === undefined
        ? {}
        : {
            query: {
              video_id: videoId,
              ...((input?.language_code ?? languageFromError) === undefined
                ? {}
                : { language_code: input?.language_code ?? languageFromError })
            }
          }),
      sourceIdentity: videoId === undefined
        ? {}
        : { canonical_url: `https://www.youtube.com/watch?v=${videoId}` },
      pagination: {
        ...(input?.cursor === undefined ? {} : { cursor: input.cursor }),
        ...(input?.page_size === undefined ? {} : { page_size: input.page_size }),
        exhausted: false
      },
      accessStatus: details.accessStatus,
      limitations: [...TRANSCRIPT_LIMITATIONS],
      rawMetadata: {
        access_method: "youtube_innertube_unofficial",
        available_tracks: tracks
      },
      code,
      message: details.message,
      retryable: details.retryable,
      data: []
    }
  );
  return youtubeTranscriptEnvelopeSchema.parse(envelope);
}

function readRetrievedAt(runtime: YoutubeTranscriptRuntime): string {
  try {
    const value = runtime.now?.() ?? new Date();
    if (!(value instanceof Date) || Number.isNaN(value.valueOf())) throw new Error();
    return value.toISOString();
  } catch {
    return new Date(0).toISOString();
  }
}

interface BoundedFetchOptions {
  fetchImpl: typeof fetch;
  maxResponseBytes: number;
  timeoutMs: number;
}

async function boundedYoutubeFetch(
  params: FetchParams,
  options: BoundedFetchOptions
): Promise<Response> {
  const url = validateTranscriptUrl(params.url);
  const timeoutSignal = AbortSignal.timeout(options.timeoutMs);
  const signal = params.signal === undefined
    ? timeoutSignal
    : AbortSignal.any([params.signal, timeoutSignal]);
  const response = await options.fetchImpl(url.toString(), {
    method: params.method ?? "GET",
    ...(params.body === undefined ? {} : { body: params.body }),
    headers: params.headers,
    redirect: "error",
    signal
  });
  if (response.status === 429) {
    await response.body?.cancel();
    throw new YoutubeTranscriptUpstreamRateLimitedError();
  }
  const declaredLength = Number(response.headers.get("content-length"));
  if (Number.isFinite(declaredLength) && declaredLength > options.maxResponseBytes) {
    await response.body?.cancel();
    throw new Error(`Upstream response exceeds ${options.maxResponseBytes} bytes`);
  }
  const bytes = await readBoundedBody(response, options.maxResponseBytes);
  return new Response(bytes.length === 0 ? null : new TextDecoder().decode(bytes), {
    status: response.status,
    statusText: response.statusText,
    headers: response.headers
  });
}

function validateTranscriptUrl(value: string): URL {
  let url: URL;
  try {
    url = new URL(value);
  } catch {
    throw new Error("Invalid upstream URL");
  }
  if (url.protocol !== "https:") throw new Error("Upstream URL must use HTTPS");
  if (!TRANSCRIPT_PROVIDER_HOSTS.has(url.hostname)) {
    throw new Error("Upstream host is not allowlisted");
  }
  if (url.username.length > 0 || url.password.length > 0) {
    throw new Error("Upstream URL must not include credentials");
  }
  return url;
}

async function readBoundedBody(response: Response, maximumBytes: number): Promise<Uint8Array> {
  const reader = response.body?.getReader();
  if (reader === undefined) return new Uint8Array();
  const chunks: Uint8Array[] = [];
  let bytes = 0;
  try {
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      bytes += value.byteLength;
      if (bytes > maximumBytes) {
        await reader.cancel();
        throw new Error(`Upstream response exceeds ${maximumBytes} bytes`);
      }
      chunks.push(value);
    }
  } finally {
    reader.releaseLock();
  }
  const result = new Uint8Array(bytes);
  let offset = 0;
  for (const chunk of chunks) {
    result.set(chunk, offset);
    offset += chunk.byteLength;
  }
  return result;
}

class YoutubeTranscriptResponseError extends Error {}
class YoutubeTranscriptUpstreamRateLimitedError extends Error {}

function providerErrorName(error: unknown): string | undefined {
  if (!(error instanceof Error)) return undefined;
  if (error.name === "TimeoutError" || error.name === "AbortError") {
    return error.name;
  }
  return error.constructor.name;
}

function unavailableLanguageDetails(error: unknown): {
  lang: string;
  availableLangs: string[];
} | undefined {
  if (
    providerErrorName(error) !== "YoutubeTranscriptNotAvailableLanguageError" ||
    typeof error !== "object" ||
    error === null
  ) {
    return undefined;
  }
  const record = error as Record<string, unknown>;
  if (
    typeof record.lang !== "string" ||
    !Array.isArray(record.availableLangs) ||
    !record.availableLangs.every((value) => typeof value === "string")
  ) {
    return undefined;
  }
  return { lang: record.lang, availableLangs: record.availableLangs as string[] };
}

