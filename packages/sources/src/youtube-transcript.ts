export type YoutubeTranscriptInput = z.input<typeof youtubeTranscriptInputSchema>;
export type YoutubeTranscriptEnvelope = z.output<typeof youtubeTranscriptEnvelopeSchema>;

export interface YoutubeTranscriptProviderRequest {
  languageCode?: string;
  signal: AbortSignal;
}

export interface YoutubeTranscriptProvider {
  listLanguages(
    videoId: string,
    request: Omit<YoutubeTranscriptProviderRequest, "languageCode">
  ): Promise<CaptionTrackInfo[]>;
  fetchTranscript(
    videoId: string,
    request: YoutubeTranscriptProviderRequest & { languageCode: string }
  ): Promise<TranscriptResult>;
}

export interface YoutubeTranscriptProviderOptions {
  fetchImpl?: typeof fetch;
  maxResponseBytes?: number;
  timeoutMs?: number;
}

export interface YoutubeTranscriptRuntime {
  provider?: YoutubeTranscriptProvider;
  now?: () => Date;
  timeoutMs?: number;
}

export function createYoutubeTranscriptProvider(
  options: YoutubeTranscriptProviderOptions = {}
): YoutubeTranscriptProvider {
  const fetchImpl = options.fetchImpl ?? fetch;
  const maxResponseBytes = options.maxResponseBytes ??
    DEFAULT_MAX_UPSTREAM_RESPONSE_BYTES;
  const timeoutMs = options.timeoutMs ?? DEFAULT_TIMEOUT_MS;
  if (!Number.isSafeInteger(maxResponseBytes) || maxResponseBytes < 1) {
    throw new Error("YouTube transcript response limit is invalid");
  }
  if (!Number.isSafeInteger(timeoutMs) || timeoutMs < 1) {
    throw new Error("YouTube transcript timeout is invalid");
  }

  const providerFetch = async (params: FetchParams): Promise<Response> =>
    boundedYoutubeFetch(params, { fetchImpl, maxResponseBytes, timeoutMs });

  const providerConfig = (signal: AbortSignal) => ({
    videoFetch: providerFetch,
    playerFetch: providerFetch,
    transcriptFetch: providerFetch,
    retries: 0,
    signal
  });

  return {
    async listLanguages(videoId, { signal }) {
      return listProviderLanguages(videoId, providerConfig(signal));
    },
    async fetchTranscript(videoId, { languageCode, signal }) {
      return fetchProviderTranscript(videoId, {
        ...providerConfig(signal),
        lang: languageCode,
        videoDetails: true
      });
    }
  };
}

export async function getYoutubeTranscript(
  input: YoutubeTranscriptInput,
  runtime: YoutubeTranscriptRuntime = {}
): Promise<YoutubeTranscriptEnvelope> {
  const parsedInput = youtubeTranscriptInputSchema.safeParse(input);
  if (!parsedInput.success) {
    return transcriptFailure("youtube_transcript_input_invalid", undefined, runtime);
  }
  const videoId = parseYoutubeVideoId(parsedInput.data.video_id_or_url);
  if (videoId === undefined) {
    return transcriptFailure("youtube_video_id_invalid", undefined, runtime);
  }

  const cursorResult = parseTranscriptCursor(parsedInput.data.cursor);
  if (cursorResult.error !== undefined) {
    return transcriptFailure(cursorResult.error, videoId, runtime, parsedInput.data);
  }
  const cursor = cursorResult.cursor;
  if (
    cursor !== undefined &&
    (
      cursor.video_id !== videoId ||
      (
        parsedInput.data.language_code !== undefined &&
        parsedInput.data.language_code !== cursor.language_code
      )
    )
  ) {
    return transcriptFailure(
      "youtube_transcript_cursor_mismatch",
      videoId,
      runtime,
      parsedInput.data
    );
  }

  const languageCode = cursor?.language_code ?? parsedInput.data.language_code;
  const timeoutMs = runtime.timeoutMs ?? DEFAULT_TIMEOUT_MS;
  if (!Number.isSafeInteger(timeoutMs) || timeoutMs < 1) {
    return transcriptFailure(
      "youtube_transcript_runtime_invalid",
      videoId,
      runtime,
      parsedInput.data
    );
  }
  const signal = AbortSignal.timeout(timeoutMs);
  const provider = runtime.provider ?? createYoutubeTranscriptProvider({ timeoutMs });

  let availableTracks: z.output<typeof youtubeTranscriptTrackSchema>[] = [];
  try {
    const parsedTracks = z.array(providerTrackSchema).min(1).max(MAX_TRACKS).safeParse(
      await provider.listLanguages(videoId, { signal })
    );
    if (!parsedTracks.success) throw new YoutubeTranscriptResponseError();
    availableTracks = parsedTracks.data.map(normalizeTrack);
    const selectedTrack = languageCode === undefined
      ? availableTracks[0]
      : availableTracks.find((track) => track.language_code === languageCode);
    if (selectedTrack === undefined) {
      return transcriptFailure(
        "youtube_transcript_language_not_available",
        videoId,
        runtime,
        parsedInput.data,
        availableTracks
      );
    }

    const parsedTranscript = providerTranscriptSchema.safeParse(
      await provider.fetchTranscript(videoId, {
        languageCode: selectedTrack.language_code,
        signal
      })
    );
    if (
      !parsedTranscript.success ||
      parsedTranscript.data.videoDetails.videoId !== videoId ||
      parsedTranscript.data.segments.some(({ lang }) => lang !== selectedTrack.language_code)
    ) {
      throw new YoutubeTranscriptResponseError();
    }
    const snapshotSha256 = await transcriptSnapshotSha256(
      selectedTrack,
      parsedTranscript.data.segments
    );
    if (cursor !== undefined && cursor.snapshot_sha256 !== snapshotSha256) {
      return transcriptFailure(
        "youtube_transcript_snapshot_changed",
        videoId,
        runtime,
        parsedInput.data,
        availableTracks
      );
    }

    const offset = cursor?.offset ?? 0;
    if (offset >= parsedTranscript.data.segments.length) {
      return transcriptFailure(
        "youtube_transcript_cursor_invalid",
        videoId,
        runtime,
        parsedInput.data,
        availableTracks
      );
    }
    return successfulTranscriptPage({
      videoId,
      cursor: parsedInput.data.cursor,
      offset,
      pageSize: parsedInput.data.page_size,
      snapshotSha256,
      selectedTrack,
      availableTracks,
      transcript: parsedTranscript.data,
      retrievedAt: readRetrievedAt(runtime)
    });
  } catch (error) {
    return transcriptFailure(
      transcriptFailureCode(error),
      videoId,
      runtime,
      parsedInput.data,
      availableTracks,
      error
    );
  }
}

interface SuccessfulPageInput {
  videoId: string;
  cursor?: string;
  offset: number;
  pageSize: number;
  snapshotSha256: string;
  selectedTrack: z.output<typeof youtubeTranscriptTrackSchema>;
  availableTracks: z.output<typeof youtubeTranscriptTrackSchema>[];
  transcript: z.output<typeof providerTranscriptSchema>;
  retrievedAt: string;
}

function successfulTranscriptPage(input: SuccessfulPageInput): YoutubeTranscriptEnvelope {
  const maximumCount = Math.min(
    input.pageSize,
    input.transcript.segments.length - input.offset
  );
  for (let count = maximumCount; count >= 1; count -= 1) {
    const data = input.transcript.segments
      .slice(input.offset, input.offset + count)
      .map((segment, index) => normalizeSegment(
        segment,
        input.videoId,
        input.offset + index
      ));
    const exhausted = input.offset + count === input.transcript.segments.length;
    const limitations = [
      ...TRANSCRIPT_LIMITATIONS,
      ...(input.selectedTrack.is_auto_generated
        ? ["The selected track is provider-identified as automatically generated."]
        : []),
      ...(!exhausted
        ? ["A continuation re-fetches the selected track and must match this page's caption snapshot SHA-256."]
        : [])
    ];
    const envelope = okEnvelope({
      provider: "youtube",
      recordType: "youtube_transcript",
      primaryIdentifier: input.videoId,
      retrievedAt: input.retrievedAt,
      query: {
        video_id: input.videoId,
        language_code: input.selectedTrack.language_code
      },
      sourceIdentity: {
        canonical_url: `https://www.youtube.com/watch?v=${input.videoId}`,
        ...(input.transcript.videoDetails.title.length === 0
          ? {}
          : { title: input.transcript.videoDetails.title }),
        ...(input.transcript.videoDetails.author.length === 0
          ? {}
          : { authors_or_channel: [input.transcript.videoDetails.author] })
      },
      pagination: {
        ...(input.cursor === undefined ? {} : { cursor: input.cursor }),
        ...(!exhausted
          ? {
              next_cursor: encodeCursor({
                v: 1,
                video_id: input.videoId,
                language_code: input.selectedTrack.language_code,
                snapshot_sha256: input.snapshotSha256,
                offset: input.offset + count
              })
            }
          : {}),
        page_size: input.pageSize,
        exhausted
      },
      accessStatus: exhausted ? "api_visible_complete" : "partial",
      limitations,
      rawMetadata: {
        access_method: "youtube_innertube_unofficial",
        provider_reported_segments: input.transcript.segments.length,
        snapshot_sha256: input.snapshotSha256,
        selected_track: input.selectedTrack,
        available_tracks: input.availableTracks
      },
      returned: data.length,
      data
    });
    const parsed = youtubeTranscriptEnvelopeSchema.safeParse(envelope);
    if (
      parsed.success &&
      new TextEncoder().encode(JSON.stringify(parsed.data)).byteLength <=
        ACTION_SAFE_RESPONSE_BYTES
    ) {
      return parsed.data;
    }
  }
  return transcriptFailure(
    "youtube_transcript_segment_too_large",
    input.videoId,
    { now: () => new Date(input.retrievedAt) },
    { video_id_or_url: input.videoId, page_size: input.pageSize },
    input.availableTracks
  );
}

function normalizeTrack(
  track: z.output<typeof providerTrackSchema>
): z.output<typeof youtubeTranscriptTrackSchema> {
  return {
    language_code: track.languageCode,
    language_name: track.languageName,
    is_auto_generated: track.isAutoGenerated
  };
}

function normalizeSegment(
  segment: z.output<typeof providerTranscriptSchema>["segments"][number],
  videoId: string,
  index: number
): z.output<typeof youtubeTranscriptSegmentSchema> {
  const startMs = Math.round(segment.offset * 1_000);
  return {
    index,
    start_ms: startMs,
    duration_ms: Math.round(segment.duration * 1_000),
    text: segment.text,
    language_code: segment.lang,
    timestamp_url: `https://www.youtube.com/watch?v=${videoId}&t=${Math.floor(startMs / 1_000)}s`
  };
}

async function transcriptSnapshotSha256(
  selectedTrack: z.output<typeof youtubeTranscriptTrackSchema>,
  segments: z.output<typeof providerTranscriptSchema>["segments"]
): Promise<string> {
  const digest = await crypto.subtle.digest(
    "SHA-256",
    new TextEncoder().encode(JSON.stringify({ selected_track: selectedTrack, segments }))
  );
  return Array.from(
    new Uint8Array(digest),
    (byte) => byte.toString(16).padStart(2, "0")
  ).join("");
}

function parseTranscriptCursor(cursor: string | undefined): {
  cursor?: z.output<typeof transcriptCursorSchema>;
  error?: "youtube_transcript_cursor_invalid";
} {
  if (cursor === undefined) return {};
  try {
    const parsed = transcriptCursorSchema.safeParse(decodeCursor(cursor));
    return parsed.success
      ? { cursor: parsed.data }
      : { error: "youtube_transcript_cursor_invalid" };
  } catch {
    return { error: "youtube_transcript_cursor_invalid" };
  }
}

type TranscriptFailureCode =
  | "youtube_transcript_input_invalid"
  | "youtube_video_id_invalid"
  | "youtube_transcript_cursor_invalid"
  | "youtube_transcript_cursor_mismatch"
  | "youtube_transcript_snapshot_changed"
  | "youtube_transcript_runtime_invalid"
  | "youtube_transcript_disabled"
  | "youtube_transcript_not_available"
  | "youtube_transcript_language_not_available"
  | "youtube_transcript_rate_limited"
  | "youtube_transcript_timeout"
  | "youtube_transcript_video_unavailable"
  | "youtube_transcript_response_invalid"
  | "youtube_transcript_segment_too_large"
  | "youtube_transcript_failed";

function transcriptFailureCode(error: unknown): TranscriptFailureCode {
  const name = providerErrorName(error);
  if (name === "YoutubeTranscriptDisabledError") {
    return "youtube_transcript_disabled";
  }
  if (name === "YoutubeTranscriptNotAvailableLanguageError") {
    return "youtube_transcript_language_not_available";
  }
  if (name === "YoutubeTranscriptNotAvailableError") {
    return "youtube_transcript_not_available";
  }
  if (
    name === "YoutubeTranscriptTooManyRequestError" ||
    error instanceof YoutubeTranscriptUpstreamRateLimitedError
  ) {
    return "youtube_transcript_rate_limited";
  }
  if (name === "TimeoutError" || name === "AbortError") {
    return "youtube_transcript_timeout";
  }
  if (name === "YoutubeTranscriptVideoUnavailableError") {
    return "youtube_transcript_video_unavailable";
  }
  if (error instanceof YoutubeTranscriptResponseError) {
    return "youtube_transcript_response_invalid";
  }
  if (
    name === "YoutubeTranscriptInvalidLangError" ||
    name === "YoutubeTranscriptInvalidVideoIdError"
  ) {
    return "youtube_transcript_response_invalid";
  }
  return "youtube_transcript_failed";
}

